// Vendors the Sand Weaver sand engine for Browse's preview (components/SandView.tsx)
// from dune-weaver-viewer's web/, which vendors it from sand-weaver (sync-engine.sh)
// and bakes the sand each table's clear leaves for it (bake-clears.mjs). Writes
// assets/sand/:
//  - index.js: the page as ONE string (engine + clears.js + scripts/sand-page.js in a
//    single inline module: the WebView loads it from a file, where imports can't load),
//    KEY (a hash of everything here, so a new engine gets a fresh cache folder) and
//    FILES (require()s of the .bin bakes, for expo-asset) and TEXTS (the clear
//    patterns' text: Android release builds name a raw resource without its
//    extension, so <stem>.thr beside <stem>.bin is "Duplicate resources");
//  - <table>-from-<rim|centre>.bin + .thr: each table's baked clear and its clear
//    pattern. A bin is copied only when its hash matches this engine, clear and sand
//    settings (the viewer's bakedName), so a stale bake fails here, not on the phone.
// Run after re-syncing / re-baking the viewer: npm run gen-sand (VIEWER=<web dir> to override).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const web = path.resolve(process.env.VIEWER ?? path.join(root, '../dune-weaver-viewer/web'))
const out = path.join(root, 'assets/sand')
const read = (f) => fs.readFileSync(path.join(web, f), 'utf8')
const fnv = (text) => {
  let h = 0x811c9dc5
  for (let i = 0; i < text.length; i++) h = Math.imul(h ^ text.charCodeAt(i), 0x01000193)
  return (h >>> 0).toString(16).padStart(8, '0')
}

// The page: every module in one scope, relative imports dropped and exports unexported.
const SOURCES = ['engine/sim/shaders.js', 'engine/sim/plow.js', 'engine/sim/thr.js', 'engine/sim/SandSim.js', 'engine/table-profiles.js', 'clears.js']
const parts = [...SOURCES.map((f) => [f, read(f)]), ['scripts/sand-page.js', fs.readFileSync(path.join(root, 'scripts/sand-page.js'), 'utf8')]]
const seen = new Map()
const body = parts
  .map(([f, src]) => {
    for (const m of src.matchAll(/^(?:export\s+)?(?:const|let|var|function|class|async\s+function)\s+(\w+)/gm)) {
      if (seen.has(m[1])) throw new Error(`${m[1]} is declared in both ${seen.get(m[1])} and ${f}: they share one scope on the page`)
      seen.set(m[1], f)
    }
    return `// --- ${f}\n${src.replace(/^import\s[\s\S]*?\sfrom\s+'\.[^']*';?[ \t]*$/gm, '').replace(/^export\s+(?=const|let|var|function|class|async)/gm, '')}`
  })
  .join('\n')
if (/^\s*(import|export)\s/m.test(body)) throw new Error('An import or export is left on the page')
const page = `<!doctype html>
<html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, user-scalable=no">
<style>html,body{margin:0;height:100%;overflow:hidden;background:transparent}canvas{position:absolute;inset:0;width:100%;height:100%;border-radius:50%}</style>
</head><body><canvas id="sand"></canvas><canvas id="ball"></canvas>
<script type="module">
${body.replaceAll('</script', '<\\/script')}
</script></body></html>
`

// The baked clears, checked as the viewer's page checks them.
const { configure, TABLES, APP_GRID, BAKED_PROFILE } = await import(pathToFileURL(path.join(web, 'clears.js')).href)
const { DEFAULT_SAND, DEFAULT_RENDER } = await import(pathToFileURL(path.join(web, 'engine/sim/SandSim.js')).href)
const engine = ['SandSim.js', 'plow.js', 'shaders.js', 'thr.js'].map((f) => read(`engine/sim/${f}`)).join('')
fs.rmSync(out, { recursive: true, force: true })
fs.mkdirSync(out, { recursive: true })
const files = []
const bakes = fs.readdirSync(path.join(web, 'clears'))
for (const [table, { clear: suffix }] of Object.entries(TABLES)) {
  for (const fromRim of [true, false]) {
    // The app's grid (clears.js APP_GRID), not the viewer page's.
    const sim = { sand: { ...DEFAULT_SAND }, render: { ...DEFAULT_RENDER }, resolution: APP_GRID.res }
    configure(sim, table, BAKED_PROFILE, APP_GRID)
    const clear = read(`engine/dw-clear/clear_from_${fromRim ? 'out' : 'in'}${suffix}.thr`)
    const stem = `${table}-from-${fromRim ? 'rim' : 'centre'}`
    const bake = `${stem}-${fnv(engine + clear + JSON.stringify(sim.sand) + sim.resolution)}.bin`
    if (!bakes.includes(bake)) throw new Error(`${bake} is missing: re-bake the viewer's clears (web/bake-clears.mjs) for this engine`)
    fs.copyFileSync(path.join(web, 'clears', bake), path.join(out, `${stem}.bin`))
    fs.writeFileSync(path.join(out, `${stem}.thr`), clear)
    files.push(`${stem}.bin`, `${stem}.thr`)
  }
}

const key = fnv(page + files.map((f) => fs.readFileSync(path.join(out, f), 'latin1')).join(''))
fs.writeFileSync(
  path.join(out, 'index.js'),
  `// Generated by scripts/gen-sand.mjs from ${path.relative(root, web)}: don't edit.\n` +
    `export const KEY = '${key}'\n` +
    `export const PAGE = ${JSON.stringify(page)}\n` +
    `export const FILES = {\n${files.filter((f) => f.endsWith('.bin')).map((f) => `  '${f}': require('./${f}'),`).join('\n')}\n}\n` +
    `export const TEXTS = {\n${files.filter((f) => f.endsWith('.thr')).map((f) => `  '${f}': ${JSON.stringify(fs.readFileSync(path.join(out, f), 'utf8'))},`).join('\n')}\n}\n`,
)
console.log(`assets/sand: page ${(page.length / 1024).toFixed(0)} KB, ${files.length} files, key ${key}`)
