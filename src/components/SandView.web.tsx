// Desktop's sand preview: the phones' sand page (SandView.tsx) in an <iframe>
// instead of a WebView, so the player, Create's preview and the sand thumbnails
// work there too. Same page and clears: the clears are prepared in the same cache
// folder (lib/sandFiles.ts), which the desktop app serves as app://cache/…, and
// the page goes in as srcdoc with a <base> there, so its XHRs find them. Being
// same-origin, the page reads window.SAND from this window, and its
// ReactNativeWebView.postMessage calls come back here. The page itself is the
// engine KEY's, so it stays untouched (a change would re-render every hub preview).
import React, { forwardRef, useEffect, useImperativeHandle, useRef, useState } from 'react'
import { View } from 'react-native'
import { File } from 'expo-file-system'
import { useLibrary } from '../stores/useLibrary'
import { useTheme } from '../stores/useTheme'
import { sandTable, type SandTable } from '../lib/tableSize'
import { prepareSand } from '../lib/sandFiles'
// @ts-ignore - generated by scripts/gen-sand.mjs (plain JS)
import { KEY, PAGE } from '../../assets/sand'

export const SAND = true
export const SAND_KEY = KEY as string
export { sandTable, type SandTable }
export interface SandState { f: number; playing: boolean; phase: 'loading' | 'clearing' | 'simulating' | 'ready' }
export interface SandHandle { play(): void; pause(): void; seek(f: number): void; speed(x: number): void }

interface Props {
  name: string
  thr?: string
  table: SandTable
  size: number
  onState?: (s: SandState) => void
  still?: number
  onStill?: (dataUrl: string) => void
  onError: (message: string) => void
}

type Message = { t: 'ready' } | { t: 'error'; message: string } | { t: 'still'; data: string } | ({ t: 'state' } & SandState)
type Player = SandHandle

// What each page reads from this window, by id.
const pages: Record<string, { sand: object; post(json: string): void }> = {}
;(globalThis as unknown as { __dwSand: typeof pages }).__dwSand = pages
let nextId = 0
// The page posts 'ready' at the end of its script; one that never does didn't start.
const START_MS = 30000

function pageFor(dir: string, id: string, overlays: [string, string][]): string {
  const at = `parent.__dwSand[${JSON.stringify(id)}]`
  const head = `<base href="${dir}"><script>window.SAND=${at}.sand;window.ReactNativeWebView={postMessage:(s)=>${at}?.post(s)}</script>`
  // The table's light over the sand and the ball, as SandView.tsx injects it.
  const light = `<script>(()=>{for(const [c,m] of ${JSON.stringify(overlays)}){const d=document.createElement('div');d.style.cssText='position:absolute;inset:0;border-radius:50%;pointer-events:none;mix-blend-mode:'+m+';background:'+c;document.body.appendChild(d)}})()</script>`
  return (PAGE as string).replace('<head>', `<head>${head}`).replace('</body>', `${light}</body>`)
}

export const SandView = forwardRef<SandHandle, Props>(function SandView({ name, thr: given, table, size, onState, still, onStill, onError }, ref) {
  const { sandLight, sandLift, sandLiftBlend } = useTheme((s) => s.colors)
  const [id] = useState(() => `sand${nextId++}`)
  const frame = useRef<HTMLIFrameElement>(null)
  const [doc, setDoc] = useState<string | null>(null)
  const latest = useRef({ onState, onStill, onError })
  latest.current = { onState, onStill, onError }
  // Commands sent before the page is up wait for it (Browse's autoplay comes first).
  const ready = useRef(false)
  const queued = useRef<((p: Player) => void)[]>([])
  const player = (): Player | undefined => (frame.current?.contentWindow as unknown as { sandPlayer?: Player } | null)?.sandPlayer
  const send = (fn: (p: Player) => void) => {
    const p = ready.current ? player() : undefined
    if (p) fn(p)
    else queued.current.push(fn)
  }
  useImperativeHandle(ref, () => ({
    play: () => send((p) => p.play()),
    pause: () => send((p) => p.pause()),
    seek: (f: number) => send((p) => p.seek(f)),
    speed: (x: number) => send((p) => p.speed(x)),
  }))

  useEffect(() => {
    let live = true
    let started: ReturnType<typeof setTimeout> | undefined
    ready.current = false
    ;(async () => {
      let thr = given
      if (thr == null) {
        const local = await useLibrary.getState().resolveThr(name)
        if (!local) throw new Error('This pattern isn’t on this computer.')
        thr = await new File(local.uri).text()
      }
      const dir = await prepareSand(table)
      if (!live) return
      pages[id] = {
        sand: { thr, table, size, ...(still ? { still: { size: still } } : {}) },
        post: (json) => {
          const m = JSON.parse(json) as Message
          if (m.t === 'ready') {
            ready.current = true
            clearTimeout(started)
            const p = player()
            for (const fn of queued.current.splice(0)) if (p) fn(p)
          } else if (m.t === 'error') latest.current.onError(m.message)
          else if (m.t === 'still') latest.current.onStill?.(m.data)
          else latest.current.onState?.({ f: m.f, playing: m.playing, phase: m.phase })
        },
      }
      started = setTimeout(() => !ready.current && latest.current.onError('The sand preview didn’t start.'), START_MS)
      setDoc(pageFor(dir, id, [[sandLight, 'multiply'], ...(sandLift ? ([[sandLift, sandLiftBlend]] as [string, string][]) : [])]))
    })().catch((e: unknown) => live && latest.current.onError(e instanceof Error ? e.message : String(e)))
    return () => {
      live = false
      clearTimeout(started)
      delete pages[id]
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps -- once per pattern and table
  }, [name, given, table])

  if (!doc) return <View style={{ width: size, height: size }} />
  return (
    <iframe
      ref={frame}
      srcDoc={doc}
      title="Sand preview"
      // Taps go to the player round it, as with the phones' WebView (the page has no controls).
      style={{ width: size, height: size, border: 0, display: 'block', background: 'transparent', colorScheme: 'normal', pointerEvents: 'none' }}
    />
  )
})
